/** WSAVA: each BCS unit above (or below) 5 ≈ 10% of ideal body weight. */
export const idealFromBcs = (kg, bcs) => kg / (1 + 0.1 * (bcs - 5));
export function assess(sp, kg, bcs, breed) {
  const ideal = idealFromBcs(kg, bcs), diffPct = (kg / ideal - 1) * 100;
  const status = bcs <= 3 ? 'under' : bcs === 4 ? 'slightly-under' : bcs === 5 ? 'ideal' : bcs <= 6 ? 'slightly-over' : bcs <= 7 ? 'over' : 'obese';
  const rate = [1, 2]; // % body weight per week (safe loss)
  const weeks = diffPct > 0 ? [Math.ceil(Math.log(ideal / kg) / Math.log(1 - rate[1] / 100)), Math.ceil(Math.log(ideal / kg) / Math.log(1 - rate[0] / 100))] : null;
  let breedNote = null;
  if (breed && breed[2] > 0) { const [, , lo, hi] = breed; breedNote = kg < lo * 0.9 ? 'below' : kg > hi * 1.1 ? 'above' : 'within'; }
  return { ideal, diffPct, status, weeks, breedNote };
}
